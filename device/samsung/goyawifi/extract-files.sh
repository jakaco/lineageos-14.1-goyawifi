# Copy the stock blobs listed in proprietary-files.txt into vendor/samsung/goyawifi.
# Usage: ./extract-files.sh /path/to/mounted/stock/system   (SM-T110 T110XXUANI7)
set -e
SRC=${1:?usage: $0 STOCK_SYSTEM_DIR}
HERE=$(cd "$(dirname "$0")" && pwd)
VENDOR=$HERE/../../../vendor/samsung/goyawifi
OUT=$VENDOR/proprietary
rm -rf "$OUT"; mkdir -p "$OUT"
MK=$VENDOR/goyawifi-vendor.mk
echo '# Generated by device/samsung/goyawifi/extract-files.sh' > "$MK"
echo 'PRODUCT_COPY_FILES += \' >> "$MK"
grep -v '^#' "$HERE/proprietary-files.txt" | grep -v '^$' | while IFS=: read -r src dst; do
    dst=${dst:-$src}
    mkdir -p "$OUT/$(dirname "$dst")"
    cp "$SRC/$src" "$OUT/$dst"
    echo "    vendor/samsung/goyawifi/proprietary/$dst:system/$dst \\" >> "$MK"
done
echo '' >> "$MK"
echo "Extracted $(find "$OUT" -type f | wc -l) files to $OUT"
